// Ruby accents (1.7.0): generated from the gold accent rules in app.css, so Ruby works exactly like
// Gold. Every gold rule is copied with data-gold -> data-ruby and its colours moved to ruby (OKLCH:
// hue 15, more chroma, a little darker so white highlights stay bright and shadows deep).
// Run from the repo root: node design/icons/ruby-css.js (re-run after changing the gold rules).
const fs = require('fs');
const path = require('path');
const H = require(path.join(__dirname, '../../app/src/main/assets/hub-core.js'));
const cssPath = path.join(__dirname, '../../app/src/main/assets/app.css');
const START = '/* ==== Ruby accents: generated by design/icons/ruby-css.js from the gold rules (do not edit) ==== */';
const END = '/* ==== end ruby accents ==== */';

function rubyHex(hex) {
  const o = H.hexToOklch(hex);
  if (!o || o.C < 0.012 || o.H < 50 || o.H > 120 || o.L > 0.93) return hex;
  const L = 0.08 + 0.55 * o.L + 0.28 * Math.pow(o.L, 4);
  const C = o.L > 0.3 ? Math.min(0.22, 0.07 + o.C * 1.6) : Math.min(0.08, o.C * 1.5 + 0.025);
  return H.oklchToHex(L, C, 13);
}
const hx = (r, g, b) => '#' + [r, g, b].map((v) => Number(v).toString(16).padStart(2, '0')).join('').toUpperCase();
function rubyText(t) {
  t = t.replace(/#[0-9a-fA-F]{6}\b/g, (m) => rubyHex(m));
  return t.replace(/rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([0-9.]+)\s*\)/g, (m, r, g, b, a) => {
    const n = rubyHex(hx(r, g, b)); if (n === hx(r, g, b)) return m;
    const v = parseInt(n.slice(1), 16); const sp = m.includes(', ') ? ', ' : ',';
    return `rgba(${(v >> 16) & 255}${sp}${(v >> 8) & 255}${sp}${v & 255}${sp}${a})`;
  });
}
let css = fs.readFileSync(cssPath, 'utf8');
if (css.includes(START)) css = css.slice(0, css.indexOf(START)) + css.slice(css.indexOf(END) + END.length);
css = css.replace(/\n+$/, '\n');
const out = [];
css.replace(/([^{}]*)\{([^{}]*)\}/g, (m, sel, body) => {
  if (!sel.includes('data-gold')) return m;
  const s = sel.replace(/\/\*[\s\S]*?\*\//g, '').trim().replace(/data-gold/g, 'data-ruby');
  out.push(`${s} {${rubyText(body.replace(/[ \t]*\/\*[\s\S]*?\*\/\n?/g, ''))}}`);
  return m;
});
css += `\n${START}\n${out.join('\n')}\n${END}\n`;
fs.writeFileSync(cssPath, css);
console.log(`${out.length} ruby rules`);
